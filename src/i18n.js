export const t = (key, vars = {}) =>
  (T[key]?.[lang === 'el' ? 0 : 1] ?? key).replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');

// Fills static HTML: data-t sets the text, data-t-title / data-t-placeholder / data-t-aria-label set attributes.
export function translate(root = document) {
  root.querySelectorAll('[data-t]').forEach(el => { el.textContent = t(el.dataset.t); });
  for (const attr of ['title', 'placeholder', 'aria-label'])
    root.querySelectorAll(`[data-t-${attr}]`).forEach(el => el.setAttribute(attr, t(el.getAttribute(`data-t-${attr}`))));
}
